#!/usr/bin/env python3
"""Map every camera mode of MiuiCamera (MASTER_PLAN P2): mode entry -> module id -> label -> module class -> support().

Reads the APK's dex code with Android build-tools `dexdump` and the default-language strings with `aapt2`.
usage: map_modes.py <MiuiCamera.apk> <out.md>
"""
import os
import re
import subprocess
import sys
import tempfile
import zipfile

APK, OUT = sys.argv[1], sys.argv[2]
BT = os.environ.get("BT", os.path.expanduser("~/Android/Sdk/build-tools/37.0.0"))

# string resource id -> English text
strings = {}
res = subprocess.run([f"{BT}/aapt2", "dump", "resources", APK], capture_output=True, text=True, errors="replace").stdout
cur = None
for line in res.splitlines():
    m = re.match(r"\s+resource (0x7f[0-9a-f]+) string/", line)
    if m:
        cur = int(m.group(1), 16)
        continue
    m = re.match(r'\s+\(\) "(.*)"$', line)
    if m and cur is not None:
        strings[cur] = m.group(1)
        cur = None

# dexdump of every classes*.dex, grouped by class and method
methods = {}  # (class, method) -> list of instruction lines
with tempfile.TemporaryDirectory() as tmp:
    with zipfile.ZipFile(APK) as z:
        dexes = [n for n in z.namelist() if re.fullmatch(r"classes\d*\.dex", n)]
        z.extractall(tmp, dexes)
    for d in dexes:
        dump = subprocess.run([f"{BT}/dexdump", "-d", os.path.join(tmp, d)], capture_output=True, text=True, errors="replace").stdout
        cls = meth = None
        for line in dump.splitlines():
            m = re.match(r"\s+Class descriptor\s+: '(L[^']+);'", line)
            if m:
                cls = m.group(1)[1:].replace("/", ".")
                continue
            m = re.match(r"\s+name\s+: '([^']+)'", line)
            if m:
                meth = m.group(1)
                continue
            ins = line.split("|", 1)[1] if "|" in line else ""
            if cls and meth and re.match(r"[0-9a-f]{4}: ", ins):  # skip the "[addr] Class.method:()" header line
                methods.setdefault((cls, meth), []).append(ins[6:])

# registry order: u3.a.<clinit> builds the entry class array
registry = []
for ins in methods.get(("u3.a", "<clinit>"), []):
    m = re.search(r"const-class v\d+, L([^;]+);", ins)
    if m:
        registry.append(m.group(1).replace("/", "."))


def consts(cls, meth):
    """Integer constants loaded in a method, in order (dexdump prints them as `// #<hex>`)."""
    return [int(m.group(1), 16) for m in re.finditer(r"// #([0-9a-f]+)", " ".join(methods.get((cls, meth), [])))]


rows = []
for cls in registry:
    mid = consts(cls, "getModuleId")
    label_ids = [c for c in consts(cls, "getModeItem") if c in strings]
    module = re.findall(r"new-instance v\d+, L([^;]+);", " ".join(methods.get((cls, "getModule"), [])))
    sup = " ".join(methods.get((cls, "support"), []))
    support = "always" if re.fullmatch(r"\s*const/4 v0, #int 1 // #1\s+return v0\s*", sup) else \
        ("never" if re.fullmatch(r"\s*const/4 v0, #int 0 // #0\s+return v0\s*", sup) else ("conditional" if sup else "-"))
    rows.append((mid[0] if mid else None, cls.split(".")[-1], strings[label_ids[0]] if label_ids else "",
                 module[0].replace("/", ".") if module else "", support))

md = ["# Camera modes of MiuiCamera (generated)\n",
      f"Source: `{os.path.basename(APK)}`, generated by `tools/camera_lab/map_modes.py`. Registry order = `u3.a` entry array.\n",
      "| Module id | Entry class | Label | Module class | support() |", "|---|---|---|---|---|"]
for mid, entry, label, module, support in rows:
    md.append(f"| {mid if mid is not None else '?'} (0x{mid:x}) | {entry} | {label} | `{module}` | {support} |" if mid is not None
              else f"| ? | {entry} | {label} | `{module}` | {support} |")
open(OUT, "w").write("\n".join(md) + "\n")
print(f"{len(rows)} mode entries -> {OUT}")
