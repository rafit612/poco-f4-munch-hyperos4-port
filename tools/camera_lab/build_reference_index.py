#!/usr/bin/env python3
"""Index the reference photo library of the camera project (MASTER_PLAN Step 17).

Sets (all on the pendrive archive):
  A = own phone photos (our ROM's output)       phone_photos_*/
  B = Xiaomi 17 / 17T Pro reference look         xiaomi17_reference_photos/
  C = POCO F4 photos by other people (stock)     other_people_pocof4_sample_photos/

Reads EXIF with exiftool and writes <out>/index.csv + <out>/SUMMARY.md.
usage: build_reference_index.py <archive dir> <out dir>
"""
import collections
import csv
import json
import os
import subprocess
import sys

ARCHIVE, OUT = sys.argv[1], sys.argv[2]
SETS = [
    ("A", "own phone (our ROM)", "phone_photos_2026-10-27"),
    ("B", "Xiaomi 17 / 17T Pro reference", "xiaomi17_reference_photos"),
    ("C", "POCO F4 by other people (stock)", "other_people_pocof4_sample_photos"),
]
TAGS = ["FileName", "Make", "Model", "LensModel", "FocalLength", "FocalLengthIn35mmFormat", "ExposureTime", "FNumber",
        "ISO", "WhiteBalance", "Flash", "ImageWidth", "ImageHeight", "DateTimeOriginal", "Software", "MIMEType"]
# web-resized sources: usable for colour/tone tendencies only, never for detail/noise
WEB_SIZED = ("photobohemian", "flickr", "review_sites")

os.makedirs(OUT, exist_ok=True)
rows = []
for set_id, desc, folder in SETS:
    root = os.path.join(ARCHIVE, folder)
    if not os.path.isdir(root):
        continue
    out = subprocess.run(["exiftool", "-json", "-n", "-r", "-q", "-q", "-ext", "jpg", "-ext", "jpeg", "-ext", "dng",
                          "-ext", "heic", "-ext", "mp4"] + [f"-{t}" for t in TAGS] + [root],
                         capture_output=True, text=True).stdout
    for e in json.loads(out or "[]"):
        rel = os.path.relpath(e["SourceFile"], ARCHIVE)
        source = rel.split(os.sep)[1] if rel.count(os.sep) >= 2 else folder
        rows.append({
            "set": set_id, "source": source, "file": rel,
            "kind": "video" if str(e.get("MIMEType", "")).startswith("video") else "photo",
            "detail_ok": "no" if any(w in rel for w in WEB_SIZED) else "yes",
            **{t: e.get(t, "") for t in TAGS if t not in ("FileName",)},
        })

fields = ["set", "source", "file", "kind", "detail_ok"] + [t for t in TAGS if t != "FileName"]
with open(os.path.join(OUT, "index.csv"), "w", newline="") as f:
    w = csv.DictWriter(f, fieldnames=fields)
    w.writeheader()
    w.writerows(rows)

# summary
md = ["# Reference photo library — index summary\n",
      "Generated by `tools/camera_lab/build_reference_index.py`. `detail_ok=no` marks web-resized sources "
      "(tone/colour only, never detail or noise).\n",
      "| Set | Meaning | Source folder | Photos | Videos | Detail-grade | Camera models |", "|---|---|---|---|---|---|---|"]
by = collections.defaultdict(list)
for r in rows:
    by[(r["set"], r["source"])].append(r)
names = {s: d for s, d, _ in SETS}
for (s, src), rs in sorted(by.items()):
    models = collections.Counter(str(r["Model"]) or "?" for r in rs).most_common(3)
    md.append(f"| {s} | {names[s]} | {src} | {sum(r['kind']=='photo' for r in rs)} | {sum(r['kind']=='video' for r in rs)} | "
              f"{sum(r['detail_ok']=='yes' and r['kind']=='photo' for r in rs)} | {', '.join(f'{m} ({n})' for m, n in models)} |")
md.append(f"\nTotal: {len(rows)} files.")
iso = collections.defaultdict(list)
for r in rows:
    if r["kind"] == "photo" and isinstance(r["ISO"], (int, float)):
        iso[r["set"]].append(r["ISO"])
md.append("\n| Set | ISO median | ISO max | photos with ISO |\n|---|---|---|---|")
for s in sorted(iso):
    v = sorted(iso[s])
    md.append(f"| {s} | {v[len(v)//2]} | {v[-1]} | {len(v)} |")
open(os.path.join(OUT, "SUMMARY.md"), "w").write("\n".join(md) + "\n")
print("\n".join(md))
